LANG_MAPS = {"vi": T_vi, "hi": T_hi, "id": T_id, "th": T_th}


def translate_tree(node, path_prefix, lang_map):
    """Recursively translate a tree, looking up leaf strings in lang_map.
    Falls back to the original English value if a translation is missing."""
    if isinstance(node, dict):
        return {k: translate_tree(v, f"{path_prefix}.{k}" if path_prefix else k, lang_map) for k, v in node.items()}
    if isinstance(node, list):
        return [translate_tree(item, f"{path_prefix}[{i}]", lang_map) for i, item in enumerate(node)]
    # Leaf string: look up by full path
    return lang_map.get(path_prefix, node)


for lang, lang_map in LANG_MAPS.items():
    translated = translate_tree(EN, "", lang_map)
    out_path = ROOT / f"{lang}.json"
    out_path.write_text(json.dumps(translated, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # Count how many strings still fall back to English
    def count_fallbacks(en_node, tr_node, prefix=""):
        miss = 0
        if isinstance(en_node, dict):
            for k in en_node:
                miss += count_fallbacks(en_node[k], tr_node[k], f"{prefix}.{k}" if prefix else k)
        elif isinstance(en_node, list):
            for i, item in enumerate(en_node):
                miss += count_fallbacks(item, tr_node[i], f"{prefix}[{i}]")
        else:
            if en_node == tr_node and prefix not in lang_map:
                miss += 1
        return miss
    misses = count_fallbacks(EN, translated)
    print(f"  ✓ {lang}.json ({misses} keys fell back to English)")

